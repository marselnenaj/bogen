#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md from package-lock.json and the license files in node_modules.
//
//   node scripts/gen-third-party-notices.mjs           # writes THIRD_PARTY_NOTICES.md
//   node scripts/gen-third-party-notices.mjs --check   # exits 1 when the file is out of date
//
// It lists what ships or runs with Bogen, not the tools that only build or test it: the packages bundled into
// the CLI, the shader runtime and the editor, and the packages npm installs next to the published package.
// Run `npm install` first, so that node_modules matches the lock file.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isPlatform, licenseOf as licenseIn, nameOf, ORDER, repoOf as repoIn, shippedPackages } from './shipped-packages.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'THIRD_PARTY_NOTICES.md');
// The packages that ship and where, shared with the release's SBOM.
const { packages, merged, label: LABEL } = shippedPackages(root);
const licenseOf = (path, entry) => licenseIn(root, path, entry);
const repoOf = (path) => repoIn(root, path);

const LICENSE_FILE = /^(licen[cs]e|copying|unlicense)([.-].*)?$/i;
const NOTICE_FILE = /^notice(\..*)?$/i;

function filesOf(dir, pattern) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => pattern.test(f) && statSync(join(dir, f)).isFile()).sort();
}

/** Copyright lines of a license file, as its authors wrote them. */
function copyrightLines(text) {
  const lines = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    const notice = /^copyright\b(?!\s+(notice|holders?|owner|license|statement|\[|\{))/i.test(line) || /^(\(c\)|©)\s*\d/i.test(line);
    if (notice && !/liable/i.test(line) && line.length < 300) lines.push(line);
  }
  return [...new Set(lines)];
}

const rows = [];
const platform = [];
for (const { path, groups } of merged.values()) {
  const entry = packages[path];
  const name = nameOf(path);
  const license = licenseOf(path, entry);
  const where = ORDER.filter((k) => groups.has(k)).map((k) => LABEL[k]).join(', ');
  if (isPlatform(entry)) {
    platform.push({ name, version: entry.version, license, where });
    continue;
  }
  const dir = join(root, path);
  const licenseFiles = filesOf(dir, LICENSE_FILE);
  const noticeFiles = filesOf(dir, NOTICE_FILE);
  const texts = licenseFiles.map((f) => readFileSync(join(dir, f), 'utf8'));
  rows.push({
    name, version: entry.version, license, where, repo: repoOf(path),
    copyright: texts.flatMap(copyrightLines),
    licenseFile: licenseFiles[0] ?? null,
    licenseText: texts[0] ?? null,
    notices: noticeFiles.map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').trim() })),
  });
}
const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true });
rows.sort(byName);
platform.sort(byName);

// One full text per license, from the first package that ships it. Every package's own copyright lines are listed apart.
const texts = new Map();
for (const row of rows) {
  if (row.licenseText && !texts.has(row.license)) texts.set(row.license, { from: `${row.name} ${row.version}`, file: row.licenseFile, text: row.licenseText.trim() });
}

const count = (key) => [...merged.values()].filter((m) => m.groups.has(key)).length;
const licenses = new Map();
for (const r of [...rows, ...platform]) licenses.set(r.license, (licenses.get(r.license) ?? 0) + 1);

const esc = (s) => String(s).replace(/\|/g, '\\|');
const fence = (text) => {
  let ticks = '```';
  while (text.includes(ticks)) ticks += '`';
  return `${ticks}text\n${text}\n${ticks}`;
};

const out = [];
out.push(`# Third-party notices

Bogen is licensed under the GNU General Public License, version 3 or later (see [LICENSE](LICENSE)). This file lists the third-party packages that ship or run with it,
with their licenses and the copyright notices those licenses ask to keep. Tools that only build or test Bogen
(TypeScript, Vite, Vitest, tsx and the like) are not part of what ships, and are not listed.

Generated by \`scripts/gen-third-party-notices.mjs\` from \`package-lock.json\` and the license files in
\`node_modules\`. Do not edit by hand. After a change to the dependencies, run:

\`\`\`sh
node scripts/gen-third-party-notices.mjs           # rewrites this file
node scripts/gen-third-party-notices.mjs --check   # exits 1 when it is out of date
\`\`\`

## Where the packages go

| Where | What it is | Packages |
| --- | --- | --- |
| CLI | \`packages/server/dist/cli.js\`, one bundle made by esbuild from the server, \`@bogen/core\` and their dependencies. Counted from the declared dependencies, so a few the bundler leaves out as unused may be listed. | ${count('cli')} |
| Shader runtime | \`packages/server/dist/shader-runtime.js\`, the page script that draws shader layers in renders. | ${count('shaders')} |
| Editor | The built editor in \`apps/editor/dist\`, copied to \`packages/server/dist/editor\`. Fonts included. | ${count('editor')} |
| npm install | Not bundled: the published package \`bogen-design\` depends on \`puppeteer-core\`, \`esbuild\` and \`tailwindcss\`, and npm installs them with what they need. | ${count('npm')} |

The bundles are minified and keep no license comments, so this file is where those notices live. It is included
in the npm package.

Other material from third parties:

- **Shaders.** Shader layers use \`@paper-design/shaders\` and \`@paper-design/shaders-react\` (Apache-2.0), listed below.
  Bogen is not affiliated with Paper or Lost Coast Labs.
- **Icons.** \`packages/core/src/icons-data.json\` is generated by \`scripts/gen-icons.ts\` from the icons in
  \`lucide-react\` (ISC), listed below.
- **Component kits.** \`packages/server/src/kits/\` draws kits after public design systems, from their public docs and
  how they behave, with no source code copied, and hands code off to their libraries, which are not bundled:
  shadcn/ui (MIT, shadcn), Radix Themes and Radix Colors (MIT, WorkOS), Bootstrap 5 and React Bootstrap (MIT, The
  Bootstrap Authors and React Bootstrap contributors), Material Design 3 (Apache-2.0, Google) with MUI (MIT) and
  Roboto (Apache-2.0), and Ionic (MIT, Drifty Co.). The kit in Ionic's iOS mode uses Inter and no assets, fonts or
  names of any platform vendor. Bogen is not affiliated with any of them.
- **Vectorize.** Tracing an image into SVG uses \`imagetracerjs\` (Unlicense, public domain), listed below.
- **Fonts.** The editor's interface font is Source Sans 3 and the brand font is Archivo, both from Fontsource
  packages under the SIL Open Font License 1.1, listed below. Fonts a design uses from Google Fonts are loaded from
  Google at run time and are not part of Bogen.

## Licenses in use

| License | Packages |
| --- | --- |
${[...licenses].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([l, n]) => `| ${esc(l)} | ${n} |`).join('\n')}

## Packages

| Package | Version | License | Where | Source |
| --- | --- | --- | --- | --- |
${rows.map((r) => `| \`${r.name}\` | ${r.version} | ${esc(r.license)} | ${r.where} | ${r.repo ? `<${r.repo}>` : ''} |`).join('\n')}
`);

if (platform.length) {
  out.push(`## Packages for one platform

Prebuilt binaries for one operating system and processor. npm installs only the ones that fit the machine.

| Package | Version | License | Where |
| --- | --- | --- | --- |
${platform.map((r) => `| \`${r.name}\` | ${r.version} | ${esc(r.license)} | ${r.where} |`).join('\n')}
`);
}

out.push(`## Copyright notices

As they appear in each package's license file. A package without a line here has none in its license file, or ships no
license file; its license is the one in its \`package.json\`.
`);
for (const r of rows) {
  if (!r.copyright.length) continue;
  out.push(`- \`${r.name}\` ${r.version}: ${r.copyright.map((c) => esc(c.replace(/\s+/g, ' '))).join('; ')}`);
}
const noFile = rows.filter((r) => !r.licenseFile);
if (noFile.length) out.push(`\nNo license file in the package: ${noFile.map((r) => `\`${r.name}\` ${r.version} (${esc(r.license)})`).join(', ')}.`);
out.push('');

const withNotice = rows.filter((r) => r.notices.length);
if (withNotice.length) {
  out.push('## NOTICE files\n\nApache-2.0 asks that a NOTICE file a package ships is passed on. These are their texts.\n');
  for (const r of withNotice) for (const n of r.notices) out.push(`### ${r.name} ${r.version}, ${n.file}\n\n${fence(n.text)}\n`);
}

out.push(`## License texts

One text per license, as the first package that uses it ships it. The copyright lines above belong in place of the
ones in these texts for every other package under the same license.
`);
for (const [license, t] of [...texts].sort((a, b) => a[0].localeCompare(b[0]))) {
  out.push(`### ${license}\n\nFrom \`${t.from}\`, file \`${t.file}\`.\n\n${fence(t.text)}\n`);
}

const result = `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== result) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: node scripts/gen-third-party-notices.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current: ${rows.length + platform.length} packages.`);
} else {
  writeFileSync(OUT, result);
  console.log(`Wrote THIRD_PARTY_NOTICES.md: ${rows.length} packages, ${platform.length} for one platform.`);
}
