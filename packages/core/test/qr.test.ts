const LONG = 'https://bogen.dev/share/' + 'abcdefghijklmnopqrstuvwxyz0123456789'.repeat(5);
const URL100 = 'https://omarchy.tail123456.ts.net:29443/canvas/7f3c9a2e-1b4d-4e8a-9c6f-2d5b8e1a3f07?page=home&node=n42';

const CASES: [name: string, text: string, level: QrLevel, version: number][] = [
  ['HELLO', 'HELLO', 'M', 1],
  ['omarchy', 'https://omarchy.tail123456.ts.net:29443/', 'M', 3],
  ['url100', URL100, 'M', 6],
  ['utf8', 'Grüße ✓', 'M', 1],
  ['long', LONG, 'M', 10],
  ['levelL', 'https://bogen.dev/', 'L', 2],
  ['levelQ', 'https://bogen.dev/', 'Q', 2],
  ['levelH', 'https://bogen.dev/', 'H', 3],
];

const rows = (m: boolean[][]) => m.map((row) => row.map((d) => (d ? '1' : '0')).join(''));

describe('qrMatrix', () => {
  for (const [name, text, level, version] of CASES) {
    it(`matches qrencode for ${name} at level ${level}`, () => {
      const m = qrMatrix(text, level);
      expect(m.length).toBe(17 + 4 * version);
      expect(rows(m)).toEqual(FIXTURES[name]);
    });
  }

  it('defaults to level M', () => {
    expect(rows(qrMatrix('HELLO'))).toEqual(FIXTURES.HELLO);
  });

  it('goes up to version 15 and no further', () => {
    expect(qrMatrix('x'.repeat(412), 'M').length).toBe(17 + 4 * 15);
    expect(() => qrMatrix('x'.repeat(413), 'M')).toThrow(/413 bytes do not fit in version 15/);
  });
});

describe('qrTerminal', () => {
  it('draws two module rows per line with the quiet zone around', () => {
    const m = qrMatrix('HELLO');
    const lines = qrTerminal(m, 2).split('\n');
    const size = 21 + 4;
    expect(lines.length).toBe(Math.ceil(size / 2));
    for (const line of lines) expect([...line].length).toBe(size);
    expect(lines[0]).toBe('█'.repeat(size));
    // The finder's top two rows: dark over dark at its sides, dark over light inside, then the light separator.
    expect(lines[1]!.slice(0, 10)).toBe('██ ▄▄▄▄▄ █');
    expect(qrTerminal(m, 2).endsWith('\n')).toBe(false);
  });
});

describe('qrSvgPath', () => {
  it('covers every dark module once, offset by the quiet zone', () => {
    const m = qrMatrix('HELLO');
    const { size, d } = qrSvgPath(m, 3);
    expect(size).toBe(21 + 6);
    expect(d.startsWith('M3 3h7v1h-7z')).toBe(true);
    const runs = [...d.matchAll(/M(\d+) (\d+)h(\d+)v1h-\3z/g)];
    expect(runs.map((r) => r[0]).join('')).toBe(d);
    const covered = runs.reduce((sum, r) => sum + Number(r[3]), 0);
    expect(covered).toBe(m.flat().filter(Boolean).length);
  });
});
